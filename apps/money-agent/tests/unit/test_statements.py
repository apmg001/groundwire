def test_sample_statement_is_read_completely(sample_bytes: bytes) -> None:
    result = StatementParser().parse(sample_bytes)
    assert len(result.rows) == 53 and result.problem_count == 0
    assert result.columns == {"date": "Txn Date", "description": "Narration",
                              "debit": "Withdrawal Amt.", "credit": "Deposit Amt.",
                              "balance": "Closing Balance"}
    first = result.rows[0]
    assert (first.posted_on, first.direction, first.amount) == (
        date(2026, 7, 1), Direction.CREDIT, Money.of(85000))
    assert first.balance == Money.of("237340.10")
    assert first.line == 6  # 4 preamble lines + header


def test_amount_column_with_type_column() -> None:
    data = (b"Date;Description;Amount;Type\n"
            b"05-Sep-2026;Swiggy order;450.00;DR\n"
            b"06-Sep-2026;Refund;450.00;CR\n")
    rows = StatementParser().parse(data).rows
    assert [(r.direction, r.amount.paise) for r in rows] == [
        (Direction.DEBIT, 45000), (Direction.CREDIT, 45000)]


def test_signed_amounts_and_dr_cr_suffixes() -> None:
    data = (b"Transaction Date,Particulars,Transaction Amount\n"
            b"2026-09-05,Netflix,-649.00\n"
            b"2026-09-06,Salary,\"85,000.00\"\n"
            b"2026-09-07,Uber,260.00 Dr\n")
    rows = StatementParser().parse(data).rows
    assert [(r.description, r.direction) for r in rows] == [
        ("Netflix", Direction.DEBIT), ("Salary", Direction.CREDIT), ("Uber", Direction.DEBIT)]


def test_unreadable_rows_are_reported_with_line_numbers_footers_are_not() -> None:
    data = (b"Date,Narration,Debit,Credit\n"
            b"01/09/2026,Rent,22000,\n"
            b"32/09/2026,Bad date,100,\n"
            b"02/09/2026,Bad amount,abc,\n"
            b"03/09/2026,,50,\n"
            b"04/09/2026,Zero,0,\n"
            b"05/09/2026,No amount,,\n"
            b"\n"
            b"Generated by the bank. Not a transaction.,,,\n")
    result = StatementParser().parse(data)
    assert [r.description for r in result.rows] == ["Rent"]
    assert [(p.line, p.reason) for p in result.problems] == [
        (3, "unreadable date"), (4, "unreadable amount"), (5, "no description"),
        (6, "zero amount"), (7, "no amount")]


@pytest.mark.parametrize("data", [b"", b"   \n", b"just,some,words\n1,2,3\n",
                                  b"Date,Narration,Debit\nnot,a,row\n"])
def test_files_without_a_transaction_table_are_rejected(data: bytes) -> None:
    with pytest.raises(StatementFormatError):
        StatementParser().parse(data)


def test_limits_are_enforced(sample_bytes: bytes) -> None:
    with pytest.raises(StatementTooLargeError):
        StatementParser(max_bytes=1_000).parse(sample_bytes)
    with pytest.raises(StatementTooLargeError):
        StatementParser(max_rows=5).parse(sample_bytes)
    with pytest.raises(ValueError):
        StatementParser(max_bytes=0)


def test_non_utf8_files_are_decoded() -> None:
    data = "Date,Narration,Debit\n01/09/2026,Café Coffee Day,250\n".encode("cp1252")
    [row] = StatementParser().parse(data).rows
    assert row.description == "Café Coffee Day"


@pytest.mark.parametrize(("text", "expected"), [
    ("05/09/2026", date(2026, 9, 5)), ("05-09-26", date(2026, 9, 5)),
    ("05 Sep 2026", date(2026, 9, 5)), ("05-Sep-26", date(2026, 9, 5)),
    ("2026-09-05", date(2026, 9, 5)), ("05/09/2026 14:32:10", date(2026, 9, 5)),
    ("Sep 05, 2026", date(2026, 9, 5)), ("", None), ("Opening balance", None),
])
def test_dates_are_day_first(text: str, expected: date | None) -> None:
    assert parse_date(text) == expected


def test_headers_are_normalised() -> None:
    assert normalise_header("Withdrawal Amt. (INR)") == "withdrawal amount"
    assert normalise_header("  Dr/Cr ") == "dr cr"


