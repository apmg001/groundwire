def _service() -> tuple[StatementService, InMemoryTransactionRepository]:
    store = InMemoryStore()
    repo = InMemoryTransactionRepository(store)
    return StatementService(InMemoryUserRepository(store), repo, StatementParser(),
                            RuleCategoriser()), repo


async def test_reuploading_never_double_counts(sample_bytes: bytes) -> None:
    service, repo = _service()
    first = await service.import_statement(USER, sample_bytes)
    again = await service.import_statement(USER, sample_bytes)
    assert (first.imported, first.duplicates) == (53, 0)
    assert (again.imported, again.duplicates) == (0, 53)
    assert (first.first_date, first.last_date) == ("2026-07-01", "2026-09-30")
    assert len(await repo.between(USER, date(2026, 1, 1), date(2026, 12, 31))) == 53


async def test_identical_rows_in_one_file_are_separate_transactions() -> None:
    service, _ = _service()
    data = (b"Date,Narration,Debit\n"
            b"01/09/2026,TEA STALL,20\n01/09/2026,TEA STALL,20\n01/09/2026,TEA STALL,20\n")
    assert (await service.import_statement(USER, data)).imported == 3
    # An overlapping upload with two of the three: nothing new.
    overlap = b"Date,Narration,Debit\n01/09/2026,TEA STALL,20\n01/09/2026,TEA STALL,20\n"
    assert (await service.import_statement(USER, overlap)).imported == 0


async def test_each_user_has_their_own_data(sample_bytes: bytes) -> None:
    service, repo = _service()
    await service.import_statement(USER, sample_bytes)
    report = await service.import_statement("someone-else-123456", sample_bytes)
    assert report.imported == 53  # same file, different user: all new
    assert await repo.date_bounds("nobody-at-all-1234") is None
